import CodeBlockWriter from "code-block-writer";

export interface EmittedFile {
  readonly path: string;
  readonly contents: string;
  readonly dispatchOps: ReadonlyArray<string>;
  readonly registryOps: ReadonlyArray<string>;
}

export const CORE_PACKAGE = "@hourglass-financial/api-factory-core";
export const GENERATOR_PACKAGE = "@hourglass-financial/api-factory";

export const createWriter = (): CodeBlockWriter =>
  new CodeBlockWriter({
    indentNumberOfSpaces: 2,
    newLine: "\n",
    useTabs: false,
  });

export const finishWriter = (writer: CodeBlockWriter): string =>
  `${writer.toString().trimEnd()}\n`;

export const stringLiteral = (value: string): string => JSON.stringify(value);

const commentLines = (value: string): ReadonlyArray<string> =>
  value.split("\n");

export const banner = (
  bullets: readonly [string, string] | readonly [string],
  prose?: string,
): string => {
  const lines = [
    "/**",
    ` * @generated by ${GENERATOR_PACKAGE} — DO NOT EDIT.`,
    " *",
    " * This file is machine-owned; hand edits are overwritten on regeneration.",
    " * Change the source of truth instead:",
    ...bullets.map((bullet) => ` *   - ${bullet}`),
  ];
  if (prose !== undefined && prose.length > 0) {
    lines.push(
      " *",
      ...commentLines(prose).map(
        (line) => ` *${line === "" ? "" : ` ${line}`}`,
      ),
    );
  }
  lines.push(" */");
  return lines.join("\n");
};

export const barrelBanner = (
  packageName: string,
  display: string,
  example: string,
): string =>
  [
    "/**",
    ` * @generated by ${GENERATOR_PACKAGE} — DO NOT EDIT.`,
    " *",
    ` * \`${packageName}\` — the ${display} client.`,
    " *",
    " * Provide one layer and call tree-shakeable operations grouped by resource:",
    " *",
    " * ```ts",
    ...commentLines(example).map((line) => ` * ${line}`),
    " * ```",
    " */",
  ].join("\n");

export const writeDoc = (writer: CodeBlockWriter, docs: string): void => {
  const lines = commentLines(docs);
  if (lines.length === 1) {
    writer.writeLine(`/** ${lines[0]} */`);
    return;
  }
  writer.writeLine("/**");
  for (const line of lines)
    writer.writeLine(` *${line === "" ? "" : ` ${line}`}`);
  writer.writeLine(" */");
};

export const writeLineComment = (
  writer: CodeBlockWriter,
  comment: string,
): void => {
  for (const line of commentLines(comment)) {
    writer.writeLine(`//${line === "" ? "" : ` ${line}`}`);
  }
};

const RULE =
  "// ---------------------------------------------------------------------------";
const OP_RULE =
  "// ===========================================================================";

export const section = (title: string, prose?: string): string => {
  const lines = [RULE, ...commentLines(title).map((line) => `// ${line}`)];
  if (prose !== undefined && prose.length > 0) {
    lines.push(
      "//",
      ...commentLines(prose).map(
        (line) => `//${line === "" ? "" : ` ${line}`}`,
      ),
    );
  }
  lines.push(RULE);
  return lines.join("\n");
};

export const schemaSection = (title: string): string => section(title);

export const operationSection = (
  qualifiedName: string,
  method: string,
  pathTemplate: string,
  paginated: boolean,
): string =>
  `${OP_RULE}\n// ${qualifiedName} — ${method} ${pathTemplate}${paginated ? " (cursor paginated)" : ""}\n${OP_RULE}`;

export const emitted = (
  path: string,
  contents: string,
  options: {
    readonly dispatchOps?: ReadonlyArray<string>;
    readonly registryOps?: ReadonlyArray<string>;
  } = {},
): EmittedFile => ({
  path,
  contents,
  dispatchOps: options.dispatchOps ?? [],
  registryOps: options.registryOps ?? [],
});

export const codeUnitCompare = (left: string, right: string): number =>
  left < right ? -1 : left > right ? 1 : 0;
